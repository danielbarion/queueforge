#!/usr/bin/env python3
"""Write site/app/scaling-data.ts from bench/scaling.py results.

Usage:
  python3 bench/scaling_site.py DIR [DIR ...]

Each DIR holds a scaling.jsonl. A later DIR replaces an earlier one's cells
for the same broker, scenario and CPU count, so pass the oldest first. A cell
is the median of its passed repeats; failed repeats are counted, not scored.
The note on each broker says which image and environment it was measured with.
"""
import json
import os
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "site", "app", "scaling-data.ts")
KINDS = ["rust", "bun", "php"]
SCENARIOS = ["weak-t", "weak"]


def load(dirs):
    cells = {}
    sources = {}
    for d in dirs:
        rows = [json.loads(line) for line in open(os.path.join(d, "scaling.jsonl")) if line.strip()]
        fresh = {}
        for row in rows:
            key = (row["kind"], row["scenario"], int(row["cpus"]))
            fresh.setdefault(key, []).append(row)
        for key, group in fresh.items():
            cells[key] = group
            sources[key[0]] = os.path.relpath(d, os.path.dirname(HERE))
    return cells, sources


def summarize(cells):
    out = {}
    for (kind, scenario, cpus), group in cells.items():
        ok = [float(r["received_s"]) for r in group if r.get("ok") == "1" and r.get("received_s")]
        out.setdefault(kind, {}).setdefault(scenario, []).append({
            "cpus": cpus,
            "rate": round(statistics.median(ok), 1) if ok else None,
            "failed": len(group) - len(ok),
            "repeats": len(group),
        })
    for kind in out.values():
        for points in kind.values():
            points.sort(key=lambda p: p["cpus"])
    return out


def render(data, sources):
    lines = [
        "// Generated by bench/scaling_site.py from bench/results/*/scaling.jsonl. Do not edit.",
        "",
        "export type ScalingPoint = { cpus: number; rate: number | null; failed: number; repeats: number };",
        "export type ScalingCurve = Partial<Record<\"weak-t\" | \"weak\", ScalingPoint[]>>;",
        "",
        "export const scalingSource: Record<string, string> = " + json.dumps({k: sources[k] for k in KINDS if k in sources}, indent=2) + ";",
        "",
        "export const scaling: Record<\"rust\" | \"bun\" | \"php\", ScalingCurve> = {",
    ]
    for kind in KINDS:
        lines.append(f"  {kind}: {{")
        for scenario in SCENARIOS:
            points = data.get(kind, {}).get(scenario)
            if not points:
                continue
            body = ", ".join(json.dumps(p, separators=(", ", ": ")) for p in points)
            lines.append(f"    \"{scenario}\": [{body}],")
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv):
    if not argv:
        raise SystemExit(__doc__)
    cells, sources = load(argv)
    open(OUT, "w").write(render(summarize(cells), sources))
    print(OUT)


if __name__ == "__main__":
    main(sys.argv[1:])
